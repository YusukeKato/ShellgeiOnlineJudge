import React from "react";
import { submissionDisplay, SubmissionState } from "../functions/submit";
import { JudgeVerdict } from "../api/types";
import { useLanguage } from "../language";

interface ResultProps {
  submissionState: SubmissionState;
}

// すべての判定について色の用途を定義し、追加時の表示漏れを型検査で検出する。
const VERDICT_TONES: Record<JudgeVerdict, string> = {
  accepted: "success",
  wrong_answer: "danger",
  wrong_image: "danger",
  wrong_text_and_image: "danger",
  execution_failure: "warning",
  judge_error: "danger",
};

const SojResult: React.FC<ResultProps> = ({ submissionState }) => {
  // 同じ提出stateから判定・出力を描画し、言語変更時も結果の対象と実データを保持する。
  const { language, text } = useLanguage();
  const display = submissionDisplay(submissionState, language);
  const success = submissionState.kind === "succeeded" ? submissionState : null;
  const running = submissionState.kind === "running";
  const error = submissionState.kind === "failed" || submissionState.kind === "validation_error";
  const executionError =
    success && ["execution_failure", "judge_error"].includes(success.response.verdict);
  const tone = success
    ? VERDICT_TONES[success.response.verdict]
    : error
      ? "danger"
      : running
        ? "info"
        : "neutral";
  return (
    <section className="panel result-panel" aria-labelledby="result-heading">
      <div className="panel-heading">
        <h2 id="result-heading">{text("結果", "Result")}</h2>
      </div>
      <div className="result-heading" role="status" aria-live="polite" aria-atomic="true">
        <span
          className="status-badge"
          data-tone={tone}
          lang={error || executionError ? "en" : undefined}
        >
          <span aria-hidden="true">
            {success?.response.verdict === "accepted"
              ? "✓ "
              : error || executionError
                ? "! "
                : "• "}
          </span>
          <span id="result-text">{display.verdict}</span>
        </span>
      </div>
      {submissionState.kind === "idle" && (
        <p className="result-empty">
          {text(
            "コマンドを実行すると、ここに結果が表示されます。",
            "Run a command to see its result here.",
          )}
        </p>
      )}
      {running && <p className="result-meta">{submissionState.problemId}</p>}
      {success && (
        <>
          <div className="result-meta">
            <span>{success.problemId}</span>
            <span>{success.response.execution.duration_ms} ms</span>
            <span>
              {text("提出ID", "Submission")} {success.response.submission_id ?? "—"}
            </span>
          </div>
          {success.response.persistence === "unavailable" && (
            <p className="result-error" lang="en">
              The result could not be saved.
            </p>
          )}
          <div className="result-section">
            <h3 className="io-label">{text("出力結果", "Output")}</h3>
            <pre className="code-output" tabIndex={0}>
              <code id="user-output-text">{display.output}</code>
            </pre>
          </div>
          {display.image && (
            <div className="result-section">
              <h3 className="io-label">{text("生成画像", "Generated image")}</h3>
              <img
                className="image-output"
                src={display.image}
                id="result-image"
                alt={text("実行したコマンドの生成画像", "Image generated by the submitted command")}
              />
            </div>
          )}
          <details className="help-details">
            <summary>{text("実行したコマンドと提出情報", "Submitted command & details")}</summary>
            <pre className="code-output" tabIndex={0}>
              <code id="shellgei-text">{display.commandStatus}</code>
            </pre>
          </details>
        </>
      )}
    </section>
  );
};

export default SojResult;
